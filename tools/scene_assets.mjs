// Generate app/src/scene/sceneAssets.ts from app/assets/scene/layout.json: static require()s only for the files that exist,
// so new Blender/Codex passes switch on without breaking the bundle when they are missing. Run after tools/build.sh.
import fs from "node:fs";
import path from "node:path";
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const scene = path.join(root, "app/assets/scene");
const layout = JSON.parse(fs.readFileSync(path.join(scene, "layout.json"), "utf8"));
const rel = (f) => `../../assets/scene/${f}`;
const has = (f) => f && fs.existsSync(path.join(scene, f));
const req = (f) => (has(f) ? `require("${rel(f)}")` : "null");
const layers = (layout.layers ?? []).filter((l) => has(l.file));
const lines = [
  "// Generated by tools/scene_assets.mjs from app/assets/scene/layout.json — do not edit.",
  "export const PASSES = {",
  `  tableBase: ${req("table_base.jpg")},`,
  `  tableSun: ${req("table_sun.jpg")},`,
  `  maskLattice: ${req("mask_lattice.jpg")},`,
  `  maskLeaves: ${req("mask_leaves.jpg")},`,
  "};",
  "export type SceneLayer = { name: string; src: number; y: number; x: number[]; z: number[]; drift: number; sway: number };",
  "export const LAYERS: SceneLayer[] = [",
  ...layers.map(
    (l) =>
      `  { name: ${JSON.stringify(l.name)}, src: ${req(l.file)}, y: ${l.y}, x: ${JSON.stringify(l.x)}, z: ${JSON.stringify(l.z)}, drift: ${l.drift ?? 0}, sway: ${l.sway ?? (/garden|tree|leaf/i.test(l.name) ? 1 : 0)} },`,
  ),
  "];",
  "",
];
fs.writeFileSync(path.join(root, "app/src/scene/sceneAssets.ts"), lines.join("\n"));
console.log(`sceneAssets: passes ${["table_base.jpg", "table_sun.jpg", "mask_lattice.jpg", "mask_leaves.jpg"].filter(has).length}/4, layers ${layers.length}`);
