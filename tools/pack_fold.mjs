// Pack the baked fold model (app/assets/fold/crane.{json,bin}, or placeholder.* until the Blender bake exists)
// into app/src/fold/foldData.ts: JSON metadata + base64 Float32 keyframe positions, so the bundle carries it with no file IO.
import fs from "node:fs";
import path from "node:path";
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "app/assets/fold");
const name = fs.existsSync(path.join(dir, "crane.json")) && !process.env.PLACEHOLDER ? "crane" : "placeholder";
const meta = JSON.parse(fs.readFileSync(path.join(dir, `${name}.json`), "utf8"));
const bin = fs.readFileSync(path.join(dir, `${name}.bin`));
const want = meta.keyframes * meta.vertexCount * 3 * 4;
if (bin.length !== want) throw new Error(`${name}.bin has ${bin.length} bytes, expected ${want}`);
const out = `// Generated by tools/pack_fold.mjs from app/assets/fold/${name}.* — do not edit.

export const FOLD_META = ${JSON.stringify(meta)};
export const FOLD_POS_B64 = "${bin.toString("base64")}";
`;
fs.writeFileSync(path.join(root, "app/src/fold/foldData.ts"), out);
console.log(`packed ${name}: V=${meta.vertexCount} T=${meta.triCount} K=${meta.keyframes} steps=${meta.steps.length} (${(out.length / 1e6).toFixed(2)} MB)`);
