#!/bin/bash
# rec.sh: record the simulator while the app runs slowed down (EXPO_PUBLIC_TIMESCALE = TS, default 0.5), then compress time
# back to 60 fps CFR demo time. Ported from ../soap-bubbles/tools/rec.sh.
# 60 Hz sim + TS 0.5 → 120 real frames per demo second, so the 60 fps output always has a new frame.
#
#   TS=0.5 OUT=render/promo/v1 tools/rec.sh                            # terminate + launch the app (installed by tools/embed.sh)
#   TS=0.5 OUT=… RAW=raw.mov tools/rec.sh                            # only process an existing recording
#
# Use ONLY the recording sim (notes/udid_rec.txt, the default). SECS = demo seconds to keep after the launch; it must cover
# app_end + card (the end-card phone keeps playing the recording), e.g. 27.4 + 3 + warm-up + margin → 37 (default; was 33 before the 90-frame warm-up).
# While recording, the app on other sims, ffmpeg and Blender are paused (SIGSTOP) and resumed afterwards (SIGCONT, also on
# exit/ctrl-C); nothing is ever killed, and node / Expo / Metro are never touched.
# Time conform: the .mov is VFR (frames only when the screen changes). Its CONTAINER timestamps are scaled with -itsscale TS
# (demo time) and then resampled to 60 fps CFR. Never setpts on decoded pts (that drifted / duplicated in earlier projects).
# Output: $OUT/raw.mov (can be deleted after checking), $OUT/screen.mp4 (1320×2868, 60 fps CFR, demo time),
#   $OUT/check.txt (distinct frames per second of screen.mp4, target 60), $OUT/filmstart.txt (app t = 0 in screen.mp4).
# Do not edit this file while a take is running (bash reads scripts as it goes).
set -euo pipefail
cd "$(dirname "$0")/.."
TS=${TS:-0.5}; OUT=${OUT:?set OUT}; SECS=${SECS:-37}; PRE=${PRE:-8}; APP=${APP:-dev.hoanghoa.origamicrane}
REC_UDID=$(cat notes/udid_rec.txt 2>/dev/null || true)
mkdir -p "$OUT"
RAW=${RAW:-}
if [[ -z "$RAW" ]]; then
  UDID=${UDID:-$REC_UDID}
  [[ -n "$UDID" ]] || { echo "set UDID (recording sim)" >&2; exit 1; }
  [[ "$UDID" == "$REC_UDID" || -n "${ANY_SIM:-}" ]] || { echo "UDID is not the recording sim ($REC_UDID); ANY_SIM=1 to force" >&2; exit 1; }
  RAW="$OUT/raw.mov"
  REAL=$(python3 -c "print(round($SECS / $TS + $PRE, 1))")
  df -g / | awk 'NR==2 && $4 < 15 {print "disk has " $4 " GB free < 15 GB, stopping"; exit 1}'
  PIDS=$(ps ax -o pid=,command= | grep -E 'CoreSimulator/Devices/[^/]+/data/Containers/Bundle/Application/.*\.app/|(^|/| )ffmpeg |Blender' \
    | grep -v "$UDID" | grep -vE 'grep|node|expo|metro' | awk '{print $1}' | tr '\n' ' ' || true)
  resume() { [[ -n "$PIDS" ]] && kill -CONT $PIDS 2>/dev/null; true; }
  trap resume EXIT
  [[ -n "$PIDS" ]] && { echo "pausing $(echo $PIDS | wc -w) processes"; kill -STOP $PIDS 2>/dev/null || true; sleep 1; }
  xcrun simctl terminate "$UDID" "$APP" 2>/dev/null || true
  rm -f "$RAW"
  # simctl recordVideo is host-exclusive: if another recording runs, wait and retry (up to RETRY × 30 s)
  for attempt in $(seq 1 "${RETRY:-20}"); do
    rm -f "$OUT/rec.log"
    xcrun simctl io "$UDID" recordVideo --codec=h264 --force "$RAW" 2>"$OUT/rec.log" & REC=$!
    until grep -qE "Recording started|rror|already in progress" "$OUT/rec.log" 2>/dev/null || ! kill -0 $REC 2>/dev/null; do sleep 0.2; done
    grep -q "Recording started" "$OUT/rec.log" && break
    echo "recordVideo busy ($(tr '\n' ' ' < "$OUT/rec.log" | cut -c1-120)), retry $attempt in 30 s"
    wait $REC 2>/dev/null || true; resume; sleep 30
    [[ -n "$PIDS" ]] && kill -STOP $PIDS 2>/dev/null || true
  done
  grep -q "Recording started" "$OUT/rec.log" || { echo "could not start recording" >&2; exit 1; }
  # EVT lines (demo times of the scene events) if the build logs them; dev builds log through Metro instead
  xcrun simctl spawn "$UDID" log stream --style compact --predicate 'eventMessage CONTAINS "EVT "' > "$OUT/evt.log" 2>/dev/null & LOGP=$!
  xcrun simctl launch "$UDID" "$APP" >/dev/null
  echo "recording $REAL s real time (TS=$TS)…"
  sleep "$REAL"; kill -INT $REC; wait $REC 2>/dev/null || true
  kill $LOGP 2>/dev/null || true
  echo "EVT lines in the log: $(grep -c 'EVT ' "$OUT/evt.log" || true)"
  resume; trap - EXIT
fi
# retried: right after the recording stops the .mov can still be finalising and the first pass fails silently
rm -f "$OUT/screen.mp4"
for attempt in 1 2 3; do
  ffmpeg -y -loglevel error -itsscale "$TS" -i "$RAW" -an -vf "fps=60,scale=1320:2868:flags=lanczos" -fps_mode cfr -r 60 \
    -c:v libx264 -preset slow -crf 13 -pix_fmt yuv420p -movflags +faststart "$OUT/screen.mp4" && break
  echo "screen.mp4 pass $attempt failed, retrying"; sleep 3
done
ffmpeg -hide_banner -i "$OUT/screen.mp4" -vf "mpdecimate=hi=1:lo=1:frac=0,showinfo" -f null - 2>&1 \
  | grep -o "pts_time:[0-9.]*" | cut -d: -f2 \
  | python3 -c "
import sys
b={}
for x in sys.stdin.read().split(): b[int(float(x))]=b.get(int(float(x)),0)+1
print('distinct frames per second (target 60): ' + ' '.join(f'{k}:{b.get(k,0)}' for k in range(max(b)+1)))" | tee "$OUT/check.txt"
python3 - "$OUT/check.txt" <<'PY' || true
import sys
v = [int(x.split(':')[1]) for x in open(sys.argv[1]).read().split('target 60): ')[1].split()]
bad = [i for i, n in enumerate(v[3:-1], 3) if n < 55]
if bad:
    print(f"WARNING: seconds {bad} have < 55 distinct frames: the app may have been frozen (another session's rec script "
          "SIGSTOPs other sims' apps; check `ps -o stat` for T) or the screen was static. Look at the take, redo it if frozen.")
PY
# robust freeze check from the raw recording itself (the encoded check above can count encoder noise on repeated frames as
# "distinct"): simctl only writes a frame when the screen changes, so a frozen app shows up as real seconds with ~0 frames
ffprobe -v error -select_streams v -show_entries packet=pts_time -of csv=p=0 "$RAW" | python3 -c "
import sys
b = {}
for x in sys.stdin.read().split():
    try: b[int(float(x))] = b.get(int(float(x)), 0) + 1
    except ValueError: pass
n = max(b) + 1
v = [b.get(k, 0) for k in range(n)]
print('raw frames per real second: ' + ' '.join(f'{k}:{v[k]}' for k in range(n)))
bad = [k for k in range(10, n - 2) if v[k] < 50]
if bad: print(f'WARNING: real seconds {bad} have < 50 raw frames: the app froze (another session SIGSTOPs sim apps?). Redo the take.')
# more than ~64 frames in a real second: the recorder's timestamps bunched up (seen on v5 t1, 65–85 /s for 20 s; a second or two of it during the launch is harmless), so the
# conformed demo time runs unevenly and the picture drifts against the beat-sheet events
fast = [k for k in range(10, n - 2) if v[k] > 64]
if len(fast) >= 4: print(f'WARNING: real seconds {fast} have > 64 raw frames: uneven recorder timestamps, the time conform drifts. Redo the take.')
" | tee "$OUT/rawcheck.txt"
tools/filmstart.sh "$OUT/screen.mp4" | tee "$OUT/filmstart.txt" || echo "filmstart: marker not found (pass --film-start by hand)"
echo "→ $OUT/screen.mp4 ($(python3 -c "import subprocess as s; print(s.run(['ffprobe','-v','error','-show_entries','format=duration','-of','csv=p=0','$OUT/screen.mp4'],capture_output=True,text=True).stdout.strip())") s)"
